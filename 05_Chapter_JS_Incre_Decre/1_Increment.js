let a =10;
// ++a; // pre increment
// pre increment means first increment the value of a and then use it in the expression
console.log(++a + a);
console.log(a);

let b =10;
b++; // post increment
// post increment means first use the current value of b in the expression and then increment it
console.log(b++ + b + ++b);
console.log(b); 
let fruit = "Banana";
switch (fruit) {
    case "Apple":
        console.log("Apple Selected");
    case "Banana":
        console.log("Banana Selected");
    case "Cherry":
        console.log("Cherry Selected");
    case "Mengo":
        console.log("Mengo Selected");
    case "Grapes":
        console.log("Grapes Selected");
    default:
        console.log("Default Reached");
}